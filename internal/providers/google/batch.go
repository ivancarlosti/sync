// The batch protocol of a Google API, and the licence lookup that needs it.
//
// A batch is how a Google API takes many calls in one request: the body is a
// `multipart/mixed` document of `application/http` parts, each one carrying a
// complete HTTP request (request line, headers, body), and the answer is the same
// shape with one part per answer. The endpoint is the `batchPath` of the API's
// discovery document, under the API's host — for the Enterprise License Manager
// API that is `https://licensing.googleapis.com/batch`.
//
// Two properties of the protocol decide how the code below is written:
//
//   - The batch itself is answered whole: a `200` means the *batch* was accepted,
//     not that its parts succeeded. Every part carries its own status, so the part
//     is what a caller inspects.
//   - The parts of an answer carry a `Content-ID` (`<response-item1>`) but are not
//     promised in the order of the request. Nothing here is correlated by position
//     or by id: a part that carries a licence carries its own product id, SKU id
//     and user id, so a reordered answer cannot mislabel a row.
package google

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"mime"
	"mime/multipart"
	"net/http"
	"net/textproto"
	"net/url"
	"strconv"
	"strings"
)

// batchPartBytes bounds one part of a batch answer, and batchBodyBytes the whole
// document. A part of the licence lookup is an assignment (a few hundred bytes) or
// an error envelope, so these are generous ceilings that keep a misbehaving
// endpoint from filling the memory of the process.
const (
	batchPartBytes = 64 << 10
	batchBodyBytes = 4 << 20
)

// batchAnswer is one part of a batch answer: the status that part answered with and
// the body it carried, which is the resource (or the error) of the sub-request.
type batchAnswer struct {
	Status int
	Body   []byte
}

// licenseProbePath is the path of one per-user licence read: the `get` of the
// Enterprise License Manager API, which is the one read of the API that takes no
// customer id — which is what makes it the answer to a catalogue the API refuses
// for the whole domain (see reportData.explainRefusal).
//
// The path is rooted at the host and not at licensingBase because a sub-request of
// a batch is relative to `licensing.googleapis.com`. Both ids and the address come
// from the catalogue and from the directory, and each is narrowed before it is
// interpolated, so no value can widen the request to another resource.
func licenseProbePath(sku reportLicenseSku, address string) (string, error) {
	if !licenseProductPattern.MatchString(sku.Product) {
		return "", invalidIdentifierError("license product", sku.Product)
	}
	if !licenseProductPattern.MatchString(sku.Sku) {
		return "", invalidIdentifierError("license sku", sku.Sku)
	}
	if !directoryKeyPattern.MatchString(address) {
		return "", invalidIdentifierError("license user", address)
	}
	return licensingPath + "/product/" + url.PathEscape(sku.Product) +
		"/sku/" + url.PathEscape(sku.Sku) +
		"/user/" + url.PathEscape(address), nil
}

// licenseProbeBody renders one batch of per-user licence lookups: one
// `application/http` part per SKU, asking for the assignment of that user.
//
// The boundary is generated by the multipart writer, so no value that came from the
// directory or from the catalogue can terminate a part. The `Content-ID` is numbered
// per part because the protocol asks for one; it is not read back, because the
// answer of a part says what it is.
func licenseProbeBody(address string, skus []reportLicenseSku) ([]byte, string, error) {
	var buffer bytes.Buffer
	writer := multipart.NewWriter(&buffer)
	for index, sku := range skus {
		path, err := licenseProbePath(sku, address)
		if err != nil {
			return nil, "", err
		}
		part, err := writer.CreatePart(textproto.MIMEHeader{
			"Content-Type": {"application/http"},
			"Content-ID":   {fmt.Sprintf("<licensing-%d>", index+1)},
		})
		if err != nil {
			return nil, "", fmt.Errorf("google licensing api: cannot build the licence batch: %w", err)
		}
		if _, err := fmt.Fprintf(part, "GET %s HTTP/1.1\r\nAccept: application/json\r\n\r\n", path); err != nil {
			return nil, "", fmt.Errorf("google licensing api: cannot build the licence batch: %w", err)
		}
	}
	if err := writer.Close(); err != nil {
		return nil, "", fmt.Errorf("google licensing api: cannot build the licence batch: %w", err)
	}
	return buffer.Bytes(), "multipart/mixed; boundary=" + writer.Boundary(), nil
}

// readBatchAnswers reads the document a batch answers with: one part per
// sub-request, each one a complete HTTP response whose status is what decides
// whether that sub-request worked.
//
// A batch that answers no part at all is an error rather than an empty success: it
// means the document was not understood, and reporting it as "nothing assigned"
// would quietly empty a section.
func readBatchAnswers(response *http.Response) ([]batchAnswer, error) {
	boundary := batchBoundary(response.Header.Get("Content-Type"))
	if boundary == "" {
		return nil, fmt.Errorf("google licensing api: the licence batch answered %q instead of a multipart document",
			response.Header.Get("Content-Type"))
	}
	reader := multipart.NewReader(io.LimitReader(response.Body, batchBodyBytes), boundary)
	answers := make([]batchAnswer, 0, len(reportLicenseSkus))
	for {
		part, err := reader.NextPart()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("google licensing api: cannot read a part of the licence batch: %w", err)
		}
		raw, err := io.ReadAll(io.LimitReader(part, batchPartBytes))
		part.Close()
		if err != nil {
			return nil, fmt.Errorf("google licensing api: cannot read a part of the licence batch: %w", err)
		}
		answer, err := parseBatchAnswer(raw)
		if err != nil {
			return nil, err
		}
		answers = append(answers, answer)
	}
	if len(answers) == 0 {
		return nil, fmt.Errorf("google licensing api: the licence batch answered no part")
	}
	return answers, nil
}

// parseBatchAnswer splits one `application/http` part into its status and body: the
// part carries a raw HTTP response, so its first line is the status line and its
// body starts after the empty line that ends the headers.
func parseBatchAnswer(raw []byte) (batchAnswer, error) {
	head, body, found := bytes.Cut(bytes.TrimLeft(raw, "\r\n"), []byte("\r\n\r\n"))
	if !found {
		return batchAnswer{}, fmt.Errorf("google licensing api: a part of the licence batch carries no status line")
	}
	fields := strings.Fields(string(head))
	if len(fields) < 2 {
		return batchAnswer{}, fmt.Errorf("google licensing api: a part of the licence batch carries no status")
	}
	status, err := strconv.Atoi(fields[1])
	if err != nil || status < 100 || status > 599 {
		return batchAnswer{}, fmt.Errorf("google licensing api: a part of the licence batch answered the status %q", fields[1])
	}
	return batchAnswer{Status: status, Body: body}, nil
}

// batchBoundary answers the boundary of a multipart Content-Type, or an empty
// string when the header does not name one.
func batchBoundary(contentType string) string {
	mediaType, params, err := mime.ParseMediaType(contentType)
	if err != nil || !strings.HasPrefix(mediaType, "multipart/") {
		return ""
	}
	return params["boundary"]
}

// batchRefusal turns a failed part of a batch into the same error shape a direct
// call answers, so a section explains it the same way whichever call carried it:
// the status and the reason of the envelope, which is what an operator reads.
//
// The label is the licence one: every batch this provider sends is a call of the
// Enterprise License Manager API, whose label client.go holds in its table.
func batchRefusal(answer batchAnswer) error {
	refusal := &apiError{Status: answer.Status, Code: answer.Status, API: "licensing api"}
	var envelope struct {
		Error struct {
			Code    int    `json:"code"`
			Message string `json:"message"`
		} `json:"error"`
	}
	if err := json.Unmarshal(answer.Body, &envelope); err == nil && envelope.Error.Message != "" {
		refusal.Message = envelope.Error.Message
		if envelope.Error.Code != 0 {
			refusal.Code = envelope.Error.Code
		}
		return refusal
	}
	// No envelope: the body is all there is, trimmed so one part of one batch
	// cannot paste a whole document into a report.
	message := strings.TrimSpace(string(answer.Body))
	if len(message) > 200 {
		message = message[:200] + "…"
	}
	refusal.Message = message
	return refusal
}
